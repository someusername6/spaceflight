/**
 * Geometry Output Generator
 *
 * Generates TypeScript output for ship geometry data.
 * Splits into multiple files for better code splitting:
 * - ship-geometry-types.ts: Types only (small, no data)
 * - ship-geometry-ships.ts: Combat ship geometry data
 * - ship-geometry-structures.ts: Station/structure geometry data
 * - ship-geometries.ts: Re-exports everything for backwards compatibility
 *
 * Used by bundle-meshes.mjs.
 */

import { writeFile } from 'node:fs/promises';

const OUTPUT_DIR = 'src/rendering';
const TYPES_FILE = `${OUTPUT_DIR}/ship-geometry-types.ts`;
const SHIPS_FILE = `${OUTPUT_DIR}/ship-geometry-ships.ts`;
const STRUCTURES_FILE = `${OUTPUT_DIR}/ship-geometry-structures.ts`;
const INDEX_FILE = `${OUTPUT_DIR}/ship-geometries.ts`;

// Structure meshes (stations, waypoints, etc.) - separate chunk
const STRUCTURE_CLASSES = new Set([
  'military',
  'mining',
  'refinery',
  'transport',
  'waypoint',
]);

/**
 * Convert a TypedArray to a string representation for embedding in JS.
 * Uses array literal for readability and smaller output than JSON.
 */
function typedArrayToString(arr) {
  const values = Array.from(arr).map((v) => {
    if (Number.isInteger(v)) return v.toString();
    return v.toFixed(6).replace(/\.?0+$/, '');
  });
  return `[${values.join(',')}]`;
}

/**
 * Format a hull plane for output
 */
function formatPlane(p) {
  return `{nx:${p.nx.toFixed(6).replace(/\.?0+$/, '')},ny:${p.ny.toFixed(6).replace(/\.?0+$/, '')},nz:${p.nz.toFixed(6).replace(/\.?0+$/, '')},d:${p.d.toFixed(6).replace(/\.?0+$/, '')}}`;
}

/**
 * Generate geometry entry for a single ship class
 */
function generateGeometryEntry(shipClass, geo) {
  const b = geo.bounds;
  const s = geo.svgBounds;
  const h = geo.hull;
  let output = `  '${shipClass}': {\n`;
  output += `    positions: ${typedArrayToString(geo.positions)},\n`;
  output += `    normals: ${geo.normals ? typedArrayToString(geo.normals) : 'null'},\n`;
  output += `    indices: ${geo.indices ? typedArrayToString(geo.indices) : 'null'},\n`;
  output += `    bounds: { minX: ${b.minX.toFixed(4)}, maxX: ${b.maxX.toFixed(4)}, minZ: ${b.minZ.toFixed(4)}, maxZ: ${b.maxZ.toFixed(4)} },\n`;
  if (s) {
    output += `    svgBounds: { minX: ${s.minX}, maxX: ${s.maxX}, minY: ${s.minY}, maxY: ${s.maxY} },\n`;
  } else {
    output += `    svgBounds: null,\n`;
  }
  if (h) {
    const hullStr = h.map(formatPlane).join(',');
    output += `    hull: [${hullStr}],\n`;
  } else {
    output += `    hull: null,\n`;
  }
  output += `    hullVolume: ${geo.hullVolume.toFixed(4)},\n`;
  output += `    hullBoundingRadius: ${geo.hullBoundingRadius.toFixed(4)},\n`;
  if (geo.subHulls && geo.subHulls.length > 0) {
    const subHullsStr = geo.subHulls
      .map(
        (sh) =>
          `{planes:[${sh.planes.map(formatPlane).join(',')}],boundingRadius:${sh.boundingRadius.toFixed(4)}}`,
      )
      .join(',');
    output += `    subHulls: [${subHullsStr}],\n`;
  } else {
    output += `    subHulls: null,\n`;
  }
  output += `  },\n`;
  return output;
}

/**
 * Generate the types file (no data, just type definitions)
 */
function generateTypesFile(shipClasses, structureClasses) {
  const allClasses = [...shipClasses, ...structureClasses].sort();
  const shipClassType = allClasses.map((c) => `'${c}'`).join(' | ');

  return `/**
 * Ship geometry types.
 * Auto-generated by scripts/build/bundle-meshes.mjs - do not edit manually.
 */

/** Valid ship class names (generated from GLB filenames) */
export type ShipClass = ${shipClassType};

/** Mesh bounding box (X and Z extents for hardpoint mapping) */
export interface MeshBounds {
  minX: number;
  maxX: number;
  minZ: number;
  maxZ: number;
}

/** SVG content bounding box (actual ship silhouette within 64x64 viewBox) */
export interface SvgBounds {
  minX: number;
  maxX: number;
  minY: number;
  maxY: number;
}

/**
 * A plane in the convex hull (normal + distance from origin).
 *
 * Note: This type is intentionally duplicated from hull-collider.ts to avoid
 * circular dependencies (ship-geometries.ts is imported by rendering code,
 * hull-collider.ts is imported by ECS code). Both definitions are identical.
 */
export interface HullPlane {
  nx: number;
  ny: number;
  nz: number;
  d: number;
}

/** Sub-hull for compound collision (connected components) */
export interface SubHull {
  planes: HullPlane[];
  boundingRadius: number;
}

/** Raw geometry data for a ship mesh */
export interface ShipGeometryData {
  positions: number[];
  normals: number[] | null;
  indices: number[] | null;
  bounds: MeshBounds;
  svgBounds: SvgBounds | null;
  /** Convex hull face planes for collision detection */
  hull: HullPlane[] | null;
  /** Volume of convex hull (for mass derivation) */
  hullVolume: number;
  /** Bounding radius of hull (for fast early-out checks) */
  hullBoundingRadius: number;
  /** Sub-hulls for compound collision (structures with disconnected parts) */
  subHulls: SubHull[] | null;
}
`;
}

/**
 * Generate a geometry data file for a subset of classes
 */
function generateDataFile(geometries, classes, exportName, description) {
  const sorted = classes.sort();
  let output = `/**
 * ${description}
 * Auto-generated by scripts/build/bundle-meshes.mjs - do not edit manually.
 */

import type { ShipGeometryData } from './ship-geometry-types';

/** ${description} */
export const ${exportName}: Record<string, ShipGeometryData> = {\n`;

  for (const shipClass of sorted) {
    const geo = geometries[shipClass];
    if (geo) {
      output += generateGeometryEntry(shipClass, geo);
    }
  }

  output += `};\n`;
  return output;
}

/**
 * Generate the index file that re-exports everything
 */
function generateIndexFile() {
  return `/**
 * Embedded ship geometry data.
 * Auto-generated by scripts/build/bundle-meshes.mjs - do not edit manually.
 *
 * This file re-exports from split modules for backwards compatibility.
 * The actual data is split into separate chunks for better loading:
 * - ship-geometry-ships.ts: Combat ship geometries
 * - ship-geometry-structures.ts: Station/structure geometries
 */

// Re-export types
export type {
  ShipClass,
  MeshBounds,
  SvgBounds,
  HullPlane,
  SubHull,
  ShipGeometryData,
} from './ship-geometry-types';

// Import data from split modules
import { SHIP_GEOMETRY_SHIPS } from './ship-geometry-ships';
import { SHIP_GEOMETRY_STRUCTURES } from './ship-geometry-structures';
import type { ShipClass, ShipGeometryData } from './ship-geometry-types';

/** Combined geometry data for all ship classes */
export const SHIP_GEOMETRIES: Record<ShipClass, ShipGeometryData> = {
  ...SHIP_GEOMETRY_SHIPS,
  ...SHIP_GEOMETRY_STRUCTURES,
} as Record<ShipClass, ShipGeometryData>;
`;
}

/**
 * Generate TypeScript output for ship geometries
 *
 * @param {Record<string, object>} geometries - Geometry data by ship class
 * @returns {Promise<void>}
 */
export async function generateGeometryOutput(geometries) {
  const allClasses = Object.keys(geometries).sort();

  if (allClasses.length === 0) {
    console.error('No valid geometries extracted');
    process.exit(1);
  }

  // Split into ships vs structures
  const shipClasses = allClasses.filter((c) => !STRUCTURE_CLASSES.has(c));
  const structureClasses = allClasses.filter((c) => STRUCTURE_CLASSES.has(c));

  // Generate all files
  const typesContent = generateTypesFile(shipClasses, structureClasses);
  const shipsContent = generateDataFile(
    geometries,
    shipClasses,
    'SHIP_GEOMETRY_SHIPS',
    'Combat ship geometry data',
  );
  const structuresContent = generateDataFile(
    geometries,
    structureClasses,
    'SHIP_GEOMETRY_STRUCTURES',
    'Station and structure geometry data',
  );
  const indexContent = generateIndexFile();

  // Write all files
  await Promise.all([
    writeFile(TYPES_FILE, typesContent),
    writeFile(SHIPS_FILE, shipsContent),
    writeFile(STRUCTURES_FILE, structuresContent),
    writeFile(INDEX_FILE, indexContent),
  ]);

  // Calculate output sizes
  const typesSize = Buffer.byteLength(typesContent, 'utf8');
  const shipsSize = Buffer.byteLength(shipsContent, 'utf8');
  const structuresSize = Buffer.byteLength(structuresContent, 'utf8');

  console.log(`\nGenerated geometry files:`);
  console.log(
    `  ${TYPES_FILE} (${(typesSize / 1024).toFixed(1)} KB) - types only`,
  );
  console.log(
    `  ${SHIPS_FILE} (${(shipsSize / 1024).toFixed(1)} KB) - ${shipClasses.length} combat ships`,
  );
  console.log(
    `  ${STRUCTURES_FILE} (${(structuresSize / 1024).toFixed(1)} KB) - ${structureClasses.length} structures`,
  );
  console.log(`  ${INDEX_FILE} - re-exports for compatibility`);
  console.log(`Embedded ${allClasses.length} total geometries`);
}
